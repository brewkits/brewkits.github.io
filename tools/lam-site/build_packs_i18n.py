"""Builds static/lam/i18n/packs.js — the Food Pack and Concert Pack sections of the landing page — from the APP's own
strings (KMP-VisionX apps/lam/shared/.../ui/i18n), so the site says exactly what the in-app showcase sheets say, in all
28 languages, with the same Japan/Taiwan photo-only variant (ConcertFilmingPolicy). Re-run after the app copy changes:

    python3 tools/lam-site/build_packs_i18n.py [path/to/KMP-VisionX]
"""
import re, json, os, sys
REPO = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/DATA/PRIVATE/KMP-VisionX")
D = REPO + "/apps/lam/shared/src/commonMain/kotlin/dev/brewkits/lam/shared/ui/i18n"
FOOD_DIR = REPO + "/apps/lam/shared/src/commonMain/kotlin/dev/brewkits/lam/shared/recipe/FoodRecipes.kt"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../static/lam/i18n/packs.js")
KEYS = ["featureFoodPack","featureFoodPackSubShare","foodPackToolsHeading","foodPackRecipesHeading","foodPackShareHeading",
 "tagGridLabel","foodToolGridBenefit","tagTungsten","foodToolRestaurantLockBenefit","tagAutoShot","foodToolAutoShotBenefit",
 "tagMoneyShot","foodToolMoneyShotBenefit","tagAsmr","foodToolAsmrBenefit","shareFrameReview","foodReviewBenefit",
 "tagMealRoll","foodMealRollBenefit","foodPackGateNote",
 "featureConcertPack","featureConcertPackSub","packSuggestionConcertPhotoSub","concertPackToolsHeadingCount",
 "followChip","concertToolFollowBenefit","stageBacktrackChip","concertToolBacktrackBenefit","stageChip",
 "concertToolStageBenefit","concertToolStagePhotoBenefit","concertToolStageBenefitPhoto","concertToolBoardName","concertToolBoardBenefit",
 "concertToolRollName","concertToolRollBenefit","shareFrameTicket","concertToolTicketBenefit","concertPackNotInPro","concertPackFooter",
 "stageFilmingSettingSub","foodPackSeeAll","concertPackSeeAll"]
STR = r'"((?:[^"\\]|\\.)*)"'
def parse(text):
    out = {}
    for k in KEYS:
        m = re.search(r'(?:override|open)\s+val\s+' + k + r'\b\s*(?::\s*String)?\s*=\s*((?:\s*' + STR + r'\s*\+?)+)', text)
        if not m: continue
        parts = re.findall(STR, m.group(1))
        s = "".join(parts)
        s = s.replace('\\"','"').replace("\\n","\n").replace("\\'","'").replace("\\$","$").replace("\\\\","\\")
        out[k] = s
    return out
base = {}
for f in sorted(os.listdir(D+"/base")):
    base.update(parse(open(D+"/base/"+f,encoding="utf-8").read()))
MAP = {"Vi":"vi","Zh":"zh","ZhHant":"zh-TW","Ja":"ja","Ko":"ko","Th":"th","Id":"id","Ms":"ms","Tl":"tl","Km":"km","Lo":"lo",
 "De":"de","Fr":"fr","Es":"es","Pt":"pt","Ar":"ar","Hi":"hi","My":"my","ArEg":"ar-EG","Fa":"fa","Uk":"uk","Ru":"ru","It":"it",
 "Nl":"nl","Sv":"sv","Pl":"pl","Tr":"tr"}
res = {"en": base}
missing = {}
for pre, lang in MAP.items():
    t = open(f"{D}/{pre}Strings.kt", encoding="utf-8").read()
    p = parse(t)
    miss = [k for k in base if k not in p]
    if miss: missing[lang] = miss
    res[lang] = {**base, **p}
if missing:
    sys.exit("locales missing pack keys (would show English): %r" % missing)
# The 7 recipes sold in the pack, in presentation order (FoodRecipes.PACK); names are not localised in the app either.
food = open(FOOD_DIR, encoding="utf-8").read()
names = dict(re.findall(r'val (FOOD_[A-Z_]+) = LamRecipe\((?:.|\n)*?name = "([^"]+)"', food))
pack_ids = re.findall(r'FOOD_[A-Z_]+', re.search(r'val PACK: List<LamRecipe> = listOf\(([^)]*)\)', food).group(1))
recipes = [names[i] for i in pack_ids]
assert len(recipes) == 7, recipes
for v in res.values():
    v.pop("concertToolStagePhotoBenefit", None)
body = json.dumps({"recipes": recipes, "photoOnly": ["ja", "zh-TW"], "s": res}, ensure_ascii=False, separators=(",", ":"))
with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* GENERATED by tools/lam-site/build_packs_i18n.py from the LAM app strings — do not edit by hand. */\n")
    f.write("window.LAM_PACKS = " + body + ";\n")
print("wrote", os.path.normpath(OUT), len(body), "bytes;", len(res), "languages; recipes:", ", ".join(recipes))
